    private static readonly Dictionary<ushort, string> IdToName = BuildIdToName();
    private static readonly Dictionary<string, ushort> NameToId = BuildNameToId();

    private static Dictionary<ushort, string> BuildIdToName()
    {
        var dict = new Dictionary<ushort, string>();
        foreach (var city in All)
        {
            dict[city.Id] = city.Name;
        }
        return dict;
    }

    private static Dictionary<string, ushort> BuildNameToId()
    {
        var dict = new Dictionary<string, ushort>();
        foreach (var city in All)
        {
            dict[city.Name] = city.Id;
        }
        return dict;
    }

    public static bool TryGetName(ushort cityId, out string name) => IdToName.TryGetValue(cityId, out name!);
    public static bool TryGetId(string cityName, out ushort id) => NameToId.TryGetValue(cityName, out id);
